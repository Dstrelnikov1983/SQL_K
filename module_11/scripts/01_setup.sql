-- ---------------------------------------------------------------------
-- 3. Контроль: сколько строк в каждой таблице
-- ---------------------------------------------------------------------
SELECT 'customers' AS table_name, COUNT(*) AS rows FROM stud_ivanov.customers
UNION ALL SELECT 'orders',               COUNT(*) FROM stud_ivanov.orders
UNION ALL SELECT 'invoices',             COUNT(*) FROM stud_ivanov.invoices
UNION ALL SELECT 'payments',             COUNT(*) FROM stud_ivanov.payments
UNION ALL SELECT 'purchase_orders',      COUNT(*) FROM stud_ivanov.purchase_orders
UNION ALL SELECT 'purchase_order_items', COUNT(*) FROM stud_ivanov.purchase_order_items
UNION ALL SELECT 'material_stock',       COUNT(*) FROM stud_ivanov.material_stock
UNION ALL SELECT 'material_requests',    COUNT(*) FROM stud_ivanov.material_requests
UNION ALL SELECT 'line_crews',           COUNT(*) FROM stud_ivanov.line_crews;
