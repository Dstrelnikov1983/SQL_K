-- График бригад на линиях (для write skew):
-- правило предприятия — на каждой линии в каждой смене минимум ОДНА бригада
CREATE TABLE stud_ivanov.line_crews (
    line_id   integer     NOT NULL REFERENCES stud_ivanov.production_lines (line_id),
    work_date date        NOT NULL,
    shift     varchar(10) NOT NULL,
    crew_name varchar(50) NOT NULL,
    on_duty   boolean     NOT NULL DEFAULT TRUE,
    PRIMARY KEY (line_id, work_date, shift, crew_name)
);
