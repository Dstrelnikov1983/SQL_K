CREATE SCHEMA IF NOT EXISTS stud_ivanov;
SET search_path TO stud_ivanov, pitanie, public;

-- ---------------------------------------------------------------------
-- 1. Копии таблиц команды А: клиенты, заказы, счета, оплаты
-- ---------------------------------------------------------------------
DROP TABLE IF EXISTS stud_ivanov.payments  CASCADE;
DROP TABLE IF EXISTS stud_ivanov.invoices  CASCADE;
DROP TABLE IF EXISTS stud_ivanov.orders    CASCADE;
DROP TABLE IF EXISTS stud_ivanov.customers CASCADE;

CREATE TABLE stud_ivanov.customers AS SELECT * FROM pitanie.customers;
ALTER TABLE stud_ivanov.customers
    ADD PRIMARY KEY (customer_id),
    -- зарезервированная (но ещё не отгруженная) часть кредитного лимита
    ADD COLUMN credit_reserved numeric(14,2) NOT NULL DEFAULT 0,
    ADD CONSTRAINT ck_customers_reserved CHECK (credit_reserved >= 0);

CREATE TABLE stud_ivanov.orders AS SELECT * FROM pitanie.orders;
ALTER TABLE stud_ivanov.orders
    ADD PRIMARY KEY (order_id),
    ADD CONSTRAINT fk_orders_customer FOREIGN KEY (customer_id)
        REFERENCES stud_ivanov.customers (customer_id);
CREATE INDEX ON stud_ivanov.orders (customer_id);

CREATE TABLE stud_ivanov.invoices AS SELECT * FROM pitanie.invoices;
ALTER TABLE stud_ivanov.invoices
    ADD PRIMARY KEY (invoice_id),
    ADD CONSTRAINT fk_invoices_order FOREIGN KEY (order_id)
        REFERENCES stud_ivanov.orders (order_id);

CREATE TABLE stud_ivanov.payments AS SELECT * FROM pitanie.payments;
ALTER TABLE stud_ivanov.payments
    ADD PRIMARY KEY (payment_id),
    ADD CONSTRAINT fk_payments_invoice FOREIGN KEY (invoice_id)
        REFERENCES stud_ivanov.invoices (invoice_id),
    ADD CONSTRAINT ck_payments_amount CHECK (amount > 0);
-- новые оплаты получают номер автоматически (5001, 5002, ...)
ALTER TABLE stud_ivanov.payments
    ALTER COLUMN payment_id ADD GENERATED BY DEFAULT AS IDENTITY (START WITH 5001);
CREATE INDEX ON stud_ivanov.payments (invoice_id);

-- ---------------------------------------------------------------------
-- 2. Копии таблиц команды Б: закупки, приёмка, сырьё, списания, линии
-- ---------------------------------------------------------------------
DROP TABLE IF EXISTS stud_ivanov.purchase_order_items CASCADE;
DROP TABLE IF EXISTS stud_ivanov.purchase_orders      CASCADE;
DROP TABLE IF EXISTS stud_ivanov.material_writeoffs   CASCADE;
DROP TABLE IF EXISTS stud_ivanov.material_stock       CASCADE;
DROP TABLE IF EXISTS stud_ivanov.material_requests    CASCADE;
DROP TABLE IF EXISTS stud_ivanov.line_crews           CASCADE;
DROP TABLE IF EXISTS stud_ivanov.raw_materials        CASCADE;
DROP TABLE IF EXISTS stud_ivanov.production_lines     CASCADE;

CREATE TABLE stud_ivanov.raw_materials AS SELECT * FROM pitanie.raw_materials;
ALTER TABLE stud_ivanov.raw_materials ADD PRIMARY KEY (material_id);

CREATE TABLE stud_ivanov.production_lines AS SELECT * FROM pitanie.production_lines;
ALTER TABLE stud_ivanov.production_lines ADD PRIMARY KEY (line_id);

CREATE TABLE stud_ivanov.purchase_orders AS SELECT * FROM pitanie.purchase_orders;
ALTER TABLE stud_ivanov.purchase_orders ADD PRIMARY KEY (po_id);

CREATE TABLE stud_ivanov.purchase_order_items AS SELECT * FROM pitanie.purchase_order_items;
ALTER TABLE stud_ivanov.purchase_order_items
    ADD PRIMARY KEY (po_item_id),
    ADD CONSTRAINT fk_poi_po FOREIGN KEY (po_id)
        REFERENCES stud_ivanov.purchase_orders (po_id),
    -- принять можно не больше заказанного
    ADD CONSTRAINT ck_poi_received CHECK (received_qty IS NULL OR received_qty <= quantity);

CREATE TABLE stud_ivanov.material_writeoffs AS SELECT * FROM pitanie.material_writeoffs;
ALTER TABLE stud_ivanov.material_writeoffs ADD PRIMARY KEY (writeoff_id);
ALTER TABLE stud_ivanov.material_writeoffs
    ALTER COLUMN writeoff_id ADD GENERATED BY DEFAULT AS IDENTITY (START WITH 1001);

-- Остатки сырья на складе на 31.12.2025:
-- принято (кроме отклонённого) − израсходовано в производстве − списано
CREATE TABLE stud_ivanov.material_stock (
    material_id integer       PRIMARY KEY REFERENCES stud_ivanov.raw_materials (material_id),
    qty_on_hand numeric(14,3) NOT NULL CHECK (qty_on_hand >= 0),
    updated_at  timestamp     NOT NULL DEFAULT now()
);
INSERT INTO stud_ivanov.material_stock (material_id, qty_on_hand, updated_at)
SELECT m.material_id,
       ROUND(  COALESCE((SELECT SUM(poi.received_qty)
                         FROM   pitanie.purchase_order_items AS poi
                         WHERE  poi.material_id = m.material_id
                           AND  poi.quality_status <> 'Отклонено'), 0)
             - COALESCE((SELECT SUM(mc.quantity)
                         FROM   pitanie.material_consumption AS mc
                         WHERE  mc.material_id = m.material_id), 0)
             - COALESCE((SELECT SUM(w.quantity)
                         FROM   pitanie.material_writeoffs AS w
                         WHERE  w.material_id = m.material_id), 0), 3),
       TIMESTAMP '2025-12-31 23:59:00'
FROM   pitanie.raw_materials AS m;

-- Очередь заявок цехов на выдачу сырья со склада (для SKIP LOCKED)
CREATE TABLE stud_ivanov.material_requests (
    request_id  integer       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    line_id     integer       NOT NULL REFERENCES stud_ivanov.production_lines (line_id),
    material_id integer       NOT NULL REFERENCES stud_ivanov.raw_materials (material_id),
    qty         numeric(14,3) NOT NULL CHECK (qty > 0),
    shift       varchar(10)   NOT NULL,
    status      varchar(20)   NOT NULL DEFAULT 'Новая',   -- Новая / Выдана
    taken_by    text,
    taken_at    timestamp
);
