-- Остатки сырья на 31.12.2025 = принято (кроме отклонённого) − расход − списания
CREATE TABLE stud_ivanov.material_stock (
    material_id integer       PRIMARY KEY REFERENCES stud_ivanov.raw_materials (material_id),
    qty_on_hand numeric(14,3) NOT NULL CHECK (qty_on_hand >= 0),
    updated_at  timestamp     NOT NULL DEFAULT now()
);
INSERT INTO stud_ivanov.material_stock (material_id, qty_on_hand, updated_at)
SELECT m.material_id,
       ROUND(  COALESCE((SELECT SUM(poi.received_qty) FROM pitanie.purchase_order_items AS poi
                         WHERE poi.material_id = m.material_id AND poi.quality_status <> 'Отклонено'), 0)
             - COALESCE((SELECT SUM(mc.quantity) FROM pitanie.material_consumption AS mc
                         WHERE mc.material_id = m.material_id), 0)
             - COALESCE((SELECT SUM(w.quantity) FROM pitanie.material_writeoffs AS w
                         WHERE w.material_id = m.material_id), 0), 3),
       TIMESTAMP '2025-12-31 23:59:00'
FROM   pitanie.raw_materials AS m;

-- ---------------------------------------------------------------------
-- 3. Таблицы результатов процедур (заполняются в лабораторной)
-- ---------------------------------------------------------------------
-- sp_close_month: итоги месяца по каналам + строка «Всего»
CREATE TABLE stud_ivanov.month_close_report (
    period_start    date          NOT NULL,
    channel         varchar(30)   NOT NULL,      -- канал или 'Всего'
    revenue         numeric(16,2) NOT NULL,
    cogs            numeric(16,2) NOT NULL,      -- себестоимость по standard_cost
    margin          numeric(16,2) NOT NULL,
    margin_pct      numeric(6,2),
    receivables     numeric(16,2),               -- дебиторка на конец месяца (строка 'Всего')
    overdue         numeric(16,2),               -- в т. ч. просроченная
    created_at      timestamp     NOT NULL DEFAULT now(),
    PRIMARY KEY (period_start, channel)
);

-- sp_block_overdue_customers: журнал блокировок
CREATE TABLE stud_ivanov.customer_block_log (
    log_id       integer       GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    customer_id  integer       NOT NULL REFERENCES stud_ivanov.customers (customer_id),
    debt         numeric(16,2) NOT NULL,
    overdue      numeric(16,2) NOT NULL,
    credit_limit numeric(16,2) NOT NULL,
    blocked_at   timestamp     NOT NULL DEFAULT now(),
    blocked_by   text          NOT NULL DEFAULT current_user
);

-- sp_reprice_below_cost: журнал изменения цен
CREATE TABLE stud_ivanov.price_change_log (
    log_id        integer       GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    product_id    integer       NOT NULL REFERENCES stud_ivanov.products (product_id),
    old_price     numeric(10,2) NOT NULL,
    new_price     numeric(10,2) NOT NULL,
    standard_cost numeric(10,2) NOT NULL,
    net_price     numeric(10,2),                 -- фактическая цена продаж с учётом скидок
    valid_from    date          NOT NULL,
    changed_at    timestamp     NOT NULL DEFAULT now()
);

-- sp_supplier_scorecard: рейтинг поставщиков за год
CREATE TABLE stud_ivanov.supplier_scorecard (
    score_year    integer       NOT NULL,
    supplier_id   integer       NOT NULL REFERENCES stud_ivanov.suppliers (supplier_id),
    items         integer       NOT NULL,
    spend         numeric(16,2) NOT NULL,
    price_index   numeric(6,3),                  -- 1.000 = средняя цена рынка по материалу
    avg_delay     numeric(6,2),                  -- среднее опоздание, дн.
    on_time_share numeric(6,3),
    quality_share numeric(6,3),                  -- доля позиций «Принято»
    score         numeric(5,2),                  -- итоговый балл 1..5
    calculated_at timestamp     NOT NULL DEFAULT now(),
    PRIMARY KEY (score_year, supplier_id)
);

-- sp_flag_lines_for_maintenance: линии, требующие ремонта / проверки
CREATE TABLE stud_ivanov.maintenance_flags (
    flag_year      integer       NOT NULL,
    line_id        integer       NOT NULL REFERENCES stud_ivanov.production_lines (line_id),
    downtime_hours numeric(10,1) NOT NULL,
    downtime_prev  numeric(10,1),
    defect_pct     numeric(6,2)  NOT NULL,
    worst_shift    varchar(10),
    worst_shift_defect_pct numeric(6,2),
    plan_pct       numeric(6,1)  NOT NULL,
    reasons        text          NOT NULL,
    flagged_at     timestamp     NOT NULL DEFAULT now(),
    PRIMARY KEY (flag_year, line_id)
);

