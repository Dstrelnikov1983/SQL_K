-- 3.3 CASE в SET: разные правила для разных групп
--     (страховой запас молочного сырья +10 %, упаковки −10 %)
BEGIN;

UPDATE raw_materials
SET    min_stock = CASE material_group
                       WHEN 'Молочное сырьё' THEN round(min_stock * 1.10, 0)
                       WHEN 'Упаковка'       THEN round(min_stock * 0.90, 0)
                       ELSE min_stock
                   END
WHERE  material_group IN ('Молочное сырьё', 'Упаковка')
RETURNING material_id, material_name, material_group, min_stock;   -- 8 строк

ROLLBACK;

-- 3.4 UPDATE ... FROM (соединение): пересчитать нормативную себестоимость
--     масла по рецептуре и средним ценам закупок IV кв. 2025
SELECT r.product_id,
       p.product_name,
       p.standard_cost,
       round(sum(r.qty_per_unit * mp.avg_price), 2) AS material_cost_q4
FROM   recipes  AS r
JOIN   products AS p ON p.product_id = r.product_id
JOIN   (SELECT poi.material_id, avg(poi.unit_price) AS avg_price
        FROM   purchase_order_items AS poi
        JOIN   purchase_orders      AS po ON po.po_id = poi.po_id
        WHERE  po.order_date >= DATE '2025-10-01'
        GROUP  BY poi.material_id) AS mp ON mp.material_id = r.material_id
WHERE  r.product_id IN (13, 14)
GROUP  BY r.product_id, p.product_name, p.standard_cost
ORDER  BY r.product_id;

BEGIN;

UPDATE products AS p
SET    standard_cost = round(c.material_cost * 1.15, 2)  -- сырьё + 15 % переработка
FROM  (SELECT r.product_id, sum(r.qty_per_unit * mp.avg_price) AS material_cost
       FROM   recipes AS r
       JOIN  (SELECT poi.material_id, avg(poi.unit_price) AS avg_price
              FROM   purchase_order_items AS poi
              JOIN   purchase_orders      AS po ON po.po_id = poi.po_id
              WHERE  po.order_date >= DATE '2025-10-01'
              GROUP  BY poi.material_id) AS mp ON mp.material_id = r.material_id
       GROUP  BY r.product_id) AS c
WHERE  c.product_id = p.product_id
  AND  p.product_id IN (13, 14)
RETURNING p.product_id, p.base_price, p.standard_cost;

ROLLBACK;

-- 3.5 UPDATE с подзапросом в WHERE: снизить кредитный лимит клиентам,
--     у которых более 3 отменённых заказов
SELECT c.customer_id, c.customer_name, c.credit_limit
FROM   customers AS c
WHERE  (SELECT count(*)
        FROM   orders AS o
        WHERE  o.customer_id = c.customer_id
          AND  o.status = 'Отменён') > 3
