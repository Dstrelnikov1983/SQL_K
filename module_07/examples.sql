BEGIN;

-- «а что если» поднять цену масла до себестоимость + 20 %?
UPDATE products
SET    base_price = ceil(standard_cost * 1.20)
WHERE  product_id IN (13, 14)
RETURNING product_id, product_name, standard_cost, base_price;

-- эффект на продажах 2025 г. (по фактическим объёмам)
SELECT p.product_name,
       sum(oi.quantity)                                                     AS qty_2025,
       round(sum(oi.quantity * (oi.unit_price * (1 - oi.discount_pct / 100)
                                - p.standard_cost)), 0)                     AS margin_fact,
       round(sum(oi.quantity * (p.base_price * (1 - oi.discount_pct / 100)
                                - p.standard_cost)), 0)                     AS margin_new_price
FROM   order_items AS oi
JOIN   orders      AS o ON o.order_id = oi.order_id
JOIN   products    AS p ON p.product_id = oi.product_id
WHERE  p.product_id IN (13, 14)
  AND  o.order_date >= DATE '2025-01-01'
  AND  o.status <> 'Отменён'
GROUP  BY p.product_name;

