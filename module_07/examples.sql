-- 6. MERGE (PostgreSQL 15+): прайс-лист 2026 -> products
-- =====================================================================
-- Источник: price_list_2026 (скрипт 02_load_price_list_2026.sql), 36 SKU.

-- 6.1 Анализ источника ДО слияния: что изменится?
SELECT CASE
           WHEN p.product_id IS NULL        THEN '3. новый SKU'
           WHEN p.base_price <> pl.price    THEN '1. цена изменилась'
           ELSE                                  '2. без изменений'
       END                  AS action,
       count(*)             AS sku_count
FROM   price_list_2026 AS pl
LEFT   JOIN products   AS p ON p.sku = pl.sku
GROUP  BY 1
ORDER  BY 1;

-- активные SKU, которых НЕТ в новом прайсе (кандидаты на вывод из ассортимента)
SELECT p.product_id, p.sku, p.product_name, p.is_active
FROM   products AS p
WHERE  NOT EXISTS (SELECT 1 FROM price_list_2026 AS pl WHERE pl.sku = p.sku);

-- 6.2 MERGE в транзакции (в лабораторной вы выполните его «по-настоящему»)
BEGIN;

MERGE INTO products AS p
USING price_list_2026 AS pl
   ON p.sku = pl.sku
WHEN MATCHED AND p.base_price <> pl.price THEN
    UPDATE SET base_price = pl.price
WHEN MATCHED THEN
    DO NOTHING
WHEN NOT MATCHED THEN
    INSERT (sku, product_name, category_id, unit, weight_kg, shelf_life_days,
            base_price, standard_cost, is_active, launch_date)
    VALUES (pl.sku, pl.product_name, pl.category_id, pl.unit, pl.weight_kg,
            pl.shelf_life_days, pl.price, pl.standard_cost, TRUE, pl.valid_from);
-- статус команды: MERGE 26 = 23 обновлено + 3 вставлено (DO NOTHING не считается)

SELECT product_id, sku, product_name, base_price
FROM   products
WHERE  product_id > 35                -- новые SKU получили id из identity
ORDER  BY product_id;

-- 6.3 WHEN NOT MATCHED BY SOURCE (есть в T-SQL и PostgreSQL 17+) в PG16 нет.
--     Обходной путь — отдельная команда в той же транзакции:
UPDATE products AS p
SET    is_active         = FALSE,
       discontinued_date = DATE '2025-12-31'
WHERE  p.is_active
  AND  NOT EXISTS (SELECT 1 FROM price_list_2026 AS pl WHERE pl.sku = p.sku)
RETURNING p.product_id, p.sku, p.product_name;

ROLLBACK;

-- 6.4 Ограничение MERGE: строка цели может совпасть только с ОДНОЙ строкой источника
-- ОЖИДАЕМАЯ ОШИБКА: MERGE command cannot affect row a second time
MERGE INTO products AS p
USING (SELECT sku, price FROM price_list_2026
       UNION ALL
       SELECT sku, price + 1 FROM price_list_2026 WHERE sku = 'MLK-001') AS pl
   ON p.sku = pl.sku
WHEN MATCHED THEN
    UPDATE SET base_price = pl.price;

-- 6.5 История цен (SCD тип 2): закрыть старую цену и открыть новую.
--     Одной MERGE не обойтись: для изменившегося SKU нужно И обновить
--     старую строку, И вставить новую. Делаем две команды в транзакции.
BEGIN;

-- шаг 1: закрыть действующие цены, которые меняются
UPDATE price_history AS ph
SET    valid_to = pl.valid_from - 1
FROM   price_list_2026 AS pl
JOIN   products        AS p ON p.sku = pl.sku
WHERE  ph.product_id = p.product_id
  AND  ph.valid_to IS NULL
  AND  ph.price <> pl.price;                                     -- UPDATE 23

-- шаг 2: открыть новые цены там, где нет действующей
INSERT INTO price_history (product_id, valid_from, valid_to, price)
SELECT p.product_id, pl.valid_from, NULL, pl.price
FROM   price_list_2026 AS pl
JOIN   products        AS p ON p.sku = pl.sku
WHERE  NOT EXISTS (SELECT 1
                   FROM   price_history AS ph
                   WHERE  ph.product_id = p.product_id
                     AND  ph.valid_to IS NULL);                  -- INSERT 23

-- контроль: у каждого товара ровно одна действующая цена
SELECT count(*)                   AS open_prices,
       count(DISTINCT product_id) AS products_with_open_price
FROM   price_history
WHERE  valid_to IS NULL;

ROLLBACK;


