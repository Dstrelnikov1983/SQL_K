WHERE  (SELECT count(*)
        FROM   orders AS o
        WHERE  o.customer_id = c.customer_id
          AND  o.status = 'Отменён') > 3;

ROLLBACK;

-- 3.6 RETURNING «старое и новое значение» в PostgreSQL 16:
--     RETURNING видит только НОВУЮ строку (OLD/NEW в RETURNING — с PG 18).
--     Приём: соединить таблицу с её же копией в FROM.
BEGIN;

UPDATE products AS p
SET    base_price = old.base_price + 10
FROM   products AS old
WHERE  old.product_id = p.product_id
  AND  p.product_id IN (13, 14)
RETURNING p.product_id, old.base_price AS old_price, p.base_price AS new_price;

ROLLBACK;

