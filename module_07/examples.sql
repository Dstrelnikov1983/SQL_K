FROM   orders
WHERE  shipped_date > required_date
ORDER  BY shipped_date - required_date DESC, order_id
LIMIT  5;

SELECT count(*) AS will_be_updated          -- 984
FROM   orders
WHERE  shipped_date > required_date;

-- 3.2 UPDATE с выражением — внутри транзакции, чтобы можно было откатить
BEGIN;

UPDATE orders
