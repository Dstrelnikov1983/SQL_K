-- =====================================================================

-- 5.1 Справочник «контакт для ЭДО» — одна строка на клиента
DROP TABLE IF EXISTS m07_edo_contact;
CREATE TABLE m07_edo_contact (
    customer_id integer PRIMARY KEY REFERENCES customers (customer_id),
    email       varchar(100) NOT NULL,
    updated_at  timestamp    NOT NULL DEFAULT now(),
    version     integer      NOT NULL DEFAULT 1
);

INSERT INTO m07_edo_contact (customer_id, email)
SELECT customer_id, lower(btrim(email))
FROM   customers
WHERE  email IS NOT NULL;                                   -- 52 строки

-- 5.2 Повторная загрузка: ON CONFLICT DO NOTHING — существующие пропускаются
INSERT INTO m07_edo_contact (customer_id, email)
VALUES (1,  'buh@vektor-td.ru'),        -- уже есть -> пропуск
       (6,  'zakaz@vkusdom.ru')         -- e-mail не было -> вставка
ON CONFLICT (customer_id) DO NOTHING
RETURNING customer_id, email;                               -- вернётся только id 6

-- 5.3 ON CONFLICT DO UPDATE: EXCLUDED — «строка, которую пытались вставить»
INSERT INTO m07_edo_contact AS t (customer_id, email)
VALUES (1,  'buh@vektor-td.ru'),
       (6,  'zakaz@vkusdom.ru'),        -- тот же адрес — менять нечего
       (7,  'edo@magnit-region.ru')
ON CONFLICT (customer_id) DO UPDATE
SET    email      = EXCLUDED.email,
       updated_at = now(),
       version    = t.version + 1
WHERE  t.email IS DISTINCT FROM EXCLUDED.email              -- не трогать без изменений
RETURNING customer_id, email, version, (xmax = 0) AS inserted;

-- 5.4 ON CONFLICT требует уникального ограничения/индекса на столбцах конфликта
-- ОЖИДАЕМАЯ ОШИБКА: there is no unique or exclusion constraint matching the ON CONFLICT specification
INSERT INTO m07_edo_contact (customer_id, email)
VALUES (1, 'buh@vektor-td.ru')
ON CONFLICT (email) DO NOTHING;

-- 5.5 Одна команда не может обновить одну строку дважды
-- ОЖИДАЕМАЯ ОШИБКА: ON CONFLICT DO UPDATE command cannot affect row a second time
INSERT INTO m07_edo_contact AS t (customer_id, email)
VALUES (5, 'a@gastronom1.ru'),
       (5, 'b@gastronom1.ru')
ON CONFLICT (customer_id) DO UPDATE SET email = EXCLUDED.email;


