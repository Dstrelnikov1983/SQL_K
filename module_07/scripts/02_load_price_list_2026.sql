-- Загрузка нового прайс-листа 2026 г. (команда А, источник для MERGE)
-- Создаёт в ТЕКУЩЕЙ (личной) схеме таблицу price_list_2026 и загружает в неё
-- данные файла module_07/data/price_list_2026.csv
-- =====================================================================
-- Перед запуском:  SET search_path TO stud_<фамилия>, pitanie, public;
-- Повторный запуск безопасен: таблица пересоздаётся.
--
-- Почему INSERT, а не COPY: серверная команда COPY ... FROM 'файл' читает
-- файл НА СЕРВЕРЕ СУБД и требует роли pg_read_server_files — в Managed
-- Service такого доступа нет. Альтернативы (файл читается на ВАШЕМ ПК):
--   * psql (после создания таблицы этим скриптом, вместо INSERT):
--     \copy price_list_2026 (sku, product_name, category_id, unit, weight_kg, shelf_life_days, price, standard_cost, valid_from) FROM 'module_07/data/price_list_2026.csv' WITH (FORMAT csv, HEADER true, DELIMITER ';', ENCODING 'UTF8')
--   * DBeaver: ПКМ по таблице -> Import Data -> CSV (разделитель «;», UTF-8).
-- =====================================================================

DO $guard$
BEGIN
    IF current_schema() IS NULL OR current_schema() IN ('pitanie', 'public') THEN
        RAISE EXCEPTION 'Текущая схема — %. Загрузка разрешена только в личную схему', current_schema()
            USING HINT = 'SET search_path TO stud_<фамилия>, pitanie, public;';
    END IF;
    EXECUTE format('DROP TABLE IF EXISTS %I.price_list_2026', current_schema());
    EXECUTE format($ddl$
        CREATE TABLE %I.price_list_2026 (
            sku             varchar(20)   PRIMARY KEY,
            product_name    varchar(150)  NOT NULL,
            category_id     integer       NOT NULL,
            unit            varchar(10)   NOT NULL,
            weight_kg       numeric(8,3)  NOT NULL,
            shelf_life_days integer       NOT NULL,
            price           numeric(10,2) NOT NULL,
            standard_cost   numeric(10,2) NOT NULL,
            valid_from      date          NOT NULL
        )$ddl$, current_schema());
    EXECUTE format('COMMENT ON TABLE %I.price_list_2026 IS %L', current_schema(), 'Прайс-лист 2026 г. от коммерческой службы (источник для MERGE)');
END
$guard$;

