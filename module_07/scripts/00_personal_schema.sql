-- =====================================================================
-- Курс «Углублённый SQL». Модуль 7 (используется также в модулях 9–12)
-- Скрипт 00: создание ЛИЧНОЙ схемы слушателя stud_<фамилия>
--            с полной копией таблиц учебной схемы pitanie
-- СУБД: PostgreSQL 16 (Yandex Managed Service for PostgreSQL)
-- =====================================================================
-- Что делает скрипт
--   1. Создаёт схему stud_<фамилия> (латиницей, строчными буквами).
--   2. Для каждой из 23 таблиц pitanie:
--        CREATE TABLE stud_x.t (LIKE pitanie.t INCLUDING ALL)
--          -- столбцы, NOT NULL, DEFAULT, CHECK, PK, UNIQUE, индексы, комментарии
--        INSERT INTO stud_x.t SELECT * FROM pitanie.t;
--   3. Восстанавливает ВСЕ внешние ключи (LIKE их не копирует).
--   4. Превращает первичные ключи в IDENTITY (GENERATED BY DEFAULT),
--      счётчик начинается с MAX(id) + 1 — новые строки можно вставлять
--      без явного указания ключа.
--   5. Устанавливает search_path = stud_<фамилия>, pitanie, public
--      и запоминает имя схемы в параметре сеанса course.stud_schema
--      (его читают скрипт сброса 01_reset_data.sql и скрипты модулей 9–12).
--
-- КАК ЗАПУСТИТЬ (выберите один способ)
--   Способ 1 (DBeaver / pgAdmin / любой клиент) — без правки файла:
--       SET course.stud_schema = 'stud_ivanov';   -- ваша фамилия
--       -- затем выполнить весь этот файл как скрипт (Alt+X в DBeaver)
--   Способ 2 — правка одной строки: найдите ниже метку  >>> ЗАМЕНИТЕ <<<
--       и впишите имя схемы вместо stud_FAMILIYA.
--   Способ 3 (psql):
--       psql "host=... port=6432 dbname=db1 user=... sslmode=verify-full sslrootcert=root.crt" \
--            -v stud=stud_ivanov -f module_07/scripts/00_personal_schema_psql.sql
--
-- Повторный запуск: если схема уже существует, скрипт остановится
-- с ошибкой (чтобы случайно не уничтожить ваши объекты из модулей 9–12).
-- Вернуть исходные данные без удаления схемы — 01_reset_data.sql.
-- Пересоздать схему «с нуля» — установите v_recreate := true
-- (ВСЕ объекты в схеме будут удалены!).
--
-- Время выполнения: 10–30 секунд (копируется ~65 тыс. строк).
-- =====================================================================

DO $personal$
DECLARE
    -- >>> ЗАМЕНИТЕ <<<  stud_FAMILIYA на свою схему, например stud_ivanov
    --                   (или заранее выполните SET course.stud_schema = 'stud_ivanov')
    v_schema   text    := coalesce(nullif(current_setting('course.stud_schema', true), ''),
                                   'stud_FAMILIYA');
    v_recreate boolean := false;   -- true = удалить схему и создать заново

    -- таблицы в порядке зависимостей (справочники -> факты)
    v_tables text[] := ARRAY[
        'regions', 'employees', 'product_categories', 'products',
        'price_history', 'customers', 'orders', 'order_items', 'invoices',
        'payments', 'returns', 'sales_plan', 'expenses',
        'suppliers', 'raw_materials', 'recipes', 'production_lines',
        'production_batches', 'material_consumption', 'equipment_downtime',
        'purchase_orders', 'purchase_order_items', 'material_writeoffs'];
    v_t      text;
    v_fk     record;
    v_pk     record;
    v_max    bigint;
    v_rows   bigint;
    v_total  bigint := 0;
BEGIN
    -- ---------- 0. Проверки имени ----------
    IF v_schema = 'stud_FAMILIYA' THEN
        RAISE EXCEPTION 'Не задано имя личной схемы'
            USING HINT = 'Выполните SET course.stud_schema = ''stud_<фамилия>''; или замените stud_FAMILIYA в скрипте';
    END IF;
    IF v_schema !~ '^[a-z_][a-z0-9_]{2,62}$' THEN
        RAISE EXCEPTION 'Имя схемы "%" недопустимо: только латиница в нижнем регистре, цифры и _', v_schema;
    END IF;
    IF v_schema IN ('pitanie', 'public') OR v_schema LIKE 'pg\_%' THEN
        RAISE EXCEPTION 'Схему % использовать как личную нельзя', v_schema;
    END IF;

    -- ---------- 1. Схема ----------
    IF EXISTS (SELECT 1 FROM pg_namespace WHERE nspname = v_schema) THEN
        IF v_recreate THEN
            EXECUTE format('DROP SCHEMA %I CASCADE', v_schema);
            RAISE NOTICE 'Схема % удалена и будет создана заново', v_schema;
        ELSE
            RAISE EXCEPTION 'Схема % уже существует', v_schema
                USING HINT = 'Для сброса данных выполните 01_reset_data.sql, для пересоздания — v_recreate := true';
        END IF;
    END IF;
    EXECUTE format('CREATE SCHEMA %I', v_schema);
    EXECUTE format('COMMENT ON SCHEMA %I IS %L', v_schema,
                   'Личная схема слушателя курса «Углублённый SQL» (копия pitanie от ' || current_date || ')');

    -- ---------- 2. Таблицы и данные ----------
    FOREACH v_t IN ARRAY v_tables LOOP
        EXECUTE format('CREATE TABLE %I.%I (LIKE pitanie.%I INCLUDING ALL)', v_schema, v_t, v_t);
        EXECUTE format('INSERT INTO %I.%I SELECT * FROM pitanie.%I', v_schema, v_t, v_t);
        GET DIAGNOSTICS v_rows = ROW_COUNT;
        v_total := v_total + v_rows;
    END LOOP;

    -- ---------- 3. Внешние ключи (копируем определения из pitanie) ----------
    FOR v_fk IN
        SELECT c.conname,
               src.relname AS src_table,
               dst.relname AS dst_table,
               (SELECT string_agg(quote_ident(a.attname), ', ' ORDER BY k.ord)
                  FROM unnest(c.conkey) WITH ORDINALITY AS k(attnum, ord)
                  JOIN pg_attribute a ON a.attrelid = c.conrelid AND a.attnum = k.attnum) AS src_cols,
               (SELECT string_agg(quote_ident(a.attname), ', ' ORDER BY k.ord)
                  FROM unnest(c.confkey) WITH ORDINALITY AS k(attnum, ord)
                  JOIN pg_attribute a ON a.attrelid = c.confrelid AND a.attnum = k.attnum) AS dst_cols
        FROM   pg_constraint c
        JOIN   pg_class src ON src.oid = c.conrelid
        JOIN   pg_class dst ON dst.oid = c.confrelid
        WHERE  c.contype = 'f'
          AND  c.connamespace = 'pitanie'::regnamespace
        ORDER  BY src.relname, c.conname
    LOOP
        EXECUTE format('ALTER TABLE %1$I.%2$I ADD CONSTRAINT %3$I FOREIGN KEY (%4$s) REFERENCES %1$I.%5$I (%6$s)',
                       v_schema, v_fk.src_table, v_fk.conname, v_fk.src_cols, v_fk.dst_table, v_fk.dst_cols);
    END LOOP;

    -- ---------- 4. IDENTITY для первичных ключей ----------
    FOR v_pk IN
        SELECT t.relname AS tbl, a.attname AS col
        FROM   pg_constraint c
        JOIN   pg_class t     ON t.oid = c.conrelid
        JOIN   pg_attribute a ON a.attrelid = c.conrelid AND a.attnum = c.conkey[1]
        WHERE  c.contype = 'p'
          AND  c.connamespace = v_schema::regnamespace
          AND  array_length(c.conkey, 1) = 1
          AND  a.atttypid IN ('integer'::regtype, 'bigint'::regtype)
    LOOP
        EXECUTE format('SELECT coalesce(max(%I), 0) + 1 FROM %I.%I', v_pk.col, v_schema, v_pk.tbl) INTO v_max;
        EXECUTE format('ALTER TABLE %I.%I ALTER COLUMN %I ADD GENERATED BY DEFAULT AS IDENTITY (START WITH %s)',
                       v_schema, v_pk.tbl, v_pk.col, v_max);
    END LOOP;

    -- ---------- 5. search_path и имя схемы для текущего сеанса ----------
    PERFORM set_config('course.stud_schema', v_schema, false);
    PERFORM set_config('search_path', format('%I, pitanie, public', v_schema), false);

    RAISE NOTICE 'Готово: схема %, таблиц %, строк скопировано %', v_schema, array_length(v_tables, 1), v_total;
END
$personal$;

-- Проверка: должно получиться 23 таблицы, строки совпадают с pitanie
SELECT current_setting('course.stud_schema', true) AS my_schema,
       current_setting('search_path')        AS search_path;

SELECT t.table_name,
       (xpath('/row/n/text()',
              query_to_xml(format('SELECT count(*) AS n FROM %I.%I',
                                  t.table_schema, t.table_name), false, true, '')))[1]::text::int AS row_count
FROM   information_schema.tables AS t
WHERE  t.table_schema = current_setting('course.stud_schema', true)
  AND  t.table_type = 'BASE TABLE'
ORDER  BY t.table_name;

-- ВАЖНО: search_path действует только в ТЕКУЩЕМ сеансе (подключении).
