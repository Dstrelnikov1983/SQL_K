-- Создаёт в ТЕКУЩЕЙ (личной) схеме таблицу supplier_price_offer и загружает в неё
-- данные файла module_07/data/supplier_price_offer.csv
-- =====================================================================
-- Перед запуском:  SET search_path TO stud_<фамилия>, pitanie, public;
-- Повторный запуск безопасен: таблица пересоздаётся.
--
-- Почему INSERT, а не COPY: серверная команда COPY ... FROM 'файл' читает
-- файл НА СЕРВЕРЕ СУБД и требует роли pg_read_server_files — в Managed
-- Service такого доступа нет. Альтернативы (файл читается на ВАШЕМ ПК):
--   * psql (после создания таблицы этим скриптом, вместо INSERT):
--     \copy supplier_price_offer (offer_id, supplier_inn, supplier_name, material_id, material_name, offer_price, min_order_qty, valid_from, valid_to) FROM 'module_07/data/supplier_price_offer.csv' WITH (FORMAT csv, HEADER true, DELIMITER ';', ENCODING 'UTF8')
--   * DBeaver: ПКМ по таблице -> Import Data -> CSV (разделитель «;», UTF-8).
-- =====================================================================

DO $guard$
BEGIN
    IF current_schema() IS NULL OR current_schema() IN ('pitanie', 'public') THEN
        RAISE EXCEPTION 'Текущая схема — %. Загрузка разрешена только в личную схему', current_schema()
            USING HINT = 'SET search_path TO stud_<фамилия>, pitanie, public;';
    END IF;
    EXECUTE format('DROP TABLE IF EXISTS %I.supplier_price_offer', current_schema());
    EXECUTE format($ddl$
        CREATE TABLE %I.supplier_price_offer (
            offer_id      integer       PRIMARY KEY,
            supplier_inn  varchar(12)   NOT NULL,
            supplier_name varchar(150)  NOT NULL,
            material_id   integer       NOT NULL,
            material_name varchar(100)  NOT NULL,
            offer_price   numeric(12,2) NOT NULL,
            min_order_qty numeric(14,2) NOT NULL,
            valid_from    date          NOT NULL,
            valid_to      date          NOT NULL
        )$ddl$, current_schema());
    EXECUTE format('COMMENT ON TABLE %I.supplier_price_offer IS %L', current_schema(), 'Коммерческие предложения поставщиков на 2026 г. (источник для MERGE)');
END
$guard$;

